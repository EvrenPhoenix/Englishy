import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = fileURLToPath(new URL("../frontend-compiled/", import.meta.url));
const output = new URL("../dist/embedded/", import.meta.url);
const types = new Map([
  [".css", "text/css; charset=utf-8"],
  [".html", "text/html; charset=utf-8"],
  [".js", "text/javascript; charset=utf-8"],
  [".png", "image/png"],
  [".svg", "image/svg+xml"],
  [".txt", "text/plain; charset=utf-8"],
  [".webmanifest", "application/manifest+json"],
  [".woff2", "font/woff2"],
  [".xml", "application/xml; charset=utf-8"],
]);
const files = Object.create(null);

async function collect(relativeDirectory = "") {
  const entries = await readdir(join(frontend, relativeDirectory), { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name, "en"));
  for (const entry of entries) {
    if (entry.name.startsWith(".") || entry.name.endsWith(".map")) continue;
    const relativePath = relativeDirectory ? relativeDirectory + "/" + entry.name : entry.name;
    if (entry.isDirectory()) {
      await collect(relativePath);
      continue;
    }
    const type = types.get(extname(entry.name));
    if (!entry.isFile() || !type) throw new Error("Unsupported frontend entry: " + relativePath);
    const bytes = await readFile(join(frontend, relativePath));
    const etag = '"' + createHash("sha256").update(bytes).digest("hex").slice(0, 20) + '"';
    const body = type === "image/png" || type === "font/woff2"
      ? { b: bytes.toString("base64") }
      : { s: bytes.toString("utf8") };
    files["/" + relativePath] = { t: type, e: etag, ...body };
  }
}

await collect();

const index = files["/index.html"]?.s;
const entry = index?.match(/<script\b[^>]*\btype="module"[^>]*\bsrc="(\/assets\/[^"]+)"/)?.[1];
if (!entry || !files[entry]) throw new Error("Missing compiled frontend entry referenced by index.html");
if (!files["/sw.js"] || !files["/offline.html"]) throw new Error("Missing offline frontend files");
const assetRoot = "/assets/";
const releaseRoot = entry.slice(0, entry.lastIndexOf("/") + 1);
const aliases = [];
if (releaseRoot !== assetRoot) {
  for (const asset of Object.keys(files)) {
    if (!asset.startsWith(assetRoot)) continue;
    const name = asset.slice(assetRoot.length);
    if (name.includes("/")) continue;
    const alias = releaseRoot + name;
    if (!files[alias]) aliases.push([alias, asset]);
  }
}

const headers = [
  {
    pattern: "/*",
    headers: {
      "Content-Security-Policy": [
        "default-src 'self'", "script-src 'self'", "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob:", "font-src 'self'", "connect-src 'self'", "media-src 'self' blob:",
        "worker-src 'self'", "manifest-src 'self'", "object-src 'none'", "base-uri 'self'",
        "form-action 'self'", "frame-ancestors 'none'",
      ].join("; "),
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "strict-origin-when-cross-origin",
      "Permissions-Policy": "microphone=(self), camera=(), geolocation=(), payment=(), usb=()",
      "Cross-Origin-Opener-Policy": "same-origin",
      "Strict-Transport-Security": "max-age=31536000; includeSubDomains",
    },
  },
  { pattern: "/assets/*", headers: { "Cache-Control": "public, max-age=31536000, immutable" } },
  { pattern: "/sw.js", headers: { "Cache-Control": "no-cache" } },
];

await mkdir(output, { recursive: true });
await writeFile(new URL("assets.js", output), [
  "// Generated by scripts/build-embedded.mjs.",
  "export const FILES = " + JSON.stringify(files) + ";",
  "for (const [alias, asset] of " + JSON.stringify(aliases) + ") FILES[alias] = FILES[asset];",
  "export const HEADER_RULES = " + JSON.stringify(headers) + ";",
  "",
].join("\n"));
console.log("Embedded " + Object.keys(files).length + " frontend files and " + aliases.length + " asset aliases.");
